export const SEO_LANG_CODES = Object.keys(SEO_LOCALES)

export function getSeoForLang(lng) {
  const base = lng?.split('-')[0]
  return SEO_LOCALES[base] || SEO_LOCALES.fr
}

export function hreflangLinks() {
  return SEO_LANG_CODES.flatMap((code) => {
    const s = SEO_LOCALES[code]
    const links = [{ hreflang: s.hreflang, href: `${SEO_SITE}${s.path === '/' ? '' : s.path}`.replace(/\/$/, '') + (s.path === '/' ? '/' : '') }]
    if (s.ogLocaleAlt) links.push({ hreflang: 'pt-PT', href: `${SEO_SITE}/pt/` })
    return links
  })
}
